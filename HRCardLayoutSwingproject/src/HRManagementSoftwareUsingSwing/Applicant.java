package HRManagementSoftwareUsingSwing;

public class Applicant {
    public final int id;
    public final String name;
    public final int age;
    public final String post;

    public Applicant(int id, String name, int age, String post) {
        this.id = id;
        this.name = name;
        this.age = age;
        this.post = post;
    }
}
